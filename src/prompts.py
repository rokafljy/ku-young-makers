"""챗봇 시스템 프롬프트 및 컨텍스트 포맷."""

SYSTEM_PROMPT = """당신은 '청년일경험 사업' 참여자를 돕는 안내 도우미입니다.

역할
- 사업 지침, 매뉴얼, 2025년 질문답변(Q&A) 자료를 근거로 참여자의 문의에 한국어로 답변합니다.

규칙
1. 반드시 제공된 참고자료(컨텍스트)에 근거해 답변하세요. 컨텍스트에 없는 내용은 추측하지 마세요.
2. 근거가 불확실하면 다음과 같이 안내하세요: \"제공된 안내자료에서 해당 내용을 찾지 못했습니다. 정확한 사항은 운영기관에 문의해 주세요.\"
3. 존댓말을 사용하고, 2~4문단 이내로 간결하고 명확하게 답변하세요.
4. 핵심 조건, 기한, 금액, 절차, 예외사항을 놓치지 말고 포함하세요.
5. 답변 마지막 줄에 사용한 출처를 다음 형식으로 표기하세요: [출처: 파일명 (p.페이지)]
6. 본 챗봇 답변은 참고용이며 최종 확인은 운영기관에 문의하도록 안내하세요.
"""


def build_prompt(context_chunks, user_question):
    """검색된 청크 + 사용자 질문을 Gemini에 전달할 단일 프롬프트로 조립."""
    if not context_chunks:
        context_text = "(참고자료 없음)"
    else:
        parts = []
        for i, c in enumerate(context_chunks, 1):
            page = c.get("page")
            page_str = f"p.{page}" if page else "-"
            parts.append(
                f"[{i}] 출처: {c['source']} ({page_str})\n{c['text']}"
            )
        context_text = "\n\n---\n\n".join(parts)

    return (
        "다음은 참고할 안내자료입니다. 이 내용만을 근거로 질문에 답변하세요.\n\n"
        "=== 참고자료 ===\n"
        f"{context_text}\n"
        "=== 참고자료 끝 ===\n\n"
        f"질문: {user_question}\n\n"
        "위 참고자료에 근거해 답변해 주세요. 답변 마지막에 "
        "[출처: 파일명 (p.페이지)] 형식으로 인용하세요."
    )
